"""
Alembic environment for the grounded schema (ADR 0005, ADR 0006 amendment).

- The connection URL comes from MIGRATION_DATABASE_URL (the migration role), never from
  alembic.ini and never from DATABASE_URL (the app role).
- The version table lives in the grounded schema, so the migration history is inside the
  schema it manages.
- The event loop is the selector loop from grounded_answers.runtime: psycopg async does
  not run on Windows' default Proactor loop.
- target_metadata is None on purpose. Migrations are explicit SQL (ADR 0005), not
  autogenerated from ORM models.
"""

import asyncio
import os
from logging.config import fileConfig

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from alembic import context
from grounded_answers.runtime import selector_loop_factory

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = None

SCHEMA = "grounded"


def _migration_url() -> str:
    url = os.environ.get("MIGRATION_DATABASE_URL")
    if not url:
        raise RuntimeError("MIGRATION_DATABASE_URL is not set (migration role; see ADR 0005)")
    return url


def run_migrations_offline() -> None:
    """Generate SQL without connecting. Not used in CI; kept for review of the SQL."""
    context.configure(
        url=_migration_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        version_table_schema=SCHEMA,
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        version_table_schema=SCHEMA,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        {"sqlalchemy.url": _migration_url()},
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations(), loop_factory=selector_loop_factory)


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
